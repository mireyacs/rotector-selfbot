/** The colour a verdict is drawn in. Falls back to body text, never to nothing. */
export function verdictColour(verdict: Verdict, palette?: ExportPalette | null): string {
    const source = palette ?? DEFAULT_PALETTE;
    return source.verdicts?.[verdict] ?? DEFAULT_VERDICT_COLOURS[verdict] ?? source.text;
}

/** `#rgb`, `#rrggbb`, `rgb()` and `rgba()` -> channels. Anything else is declined. */
export function parseColour(value: string | null | undefined): [number, number, number] | null {
    const text = String(value ?? "").trim();
    if (!text) return null;
    if (text.startsWith("#")) {
        const body = text.slice(1);
        if (body.length === 3 && /^[0-9a-f]{3}$/i.test(body)) {
            return [
                parseInt(body[0] + body[0], 16),
                parseInt(body[1] + body[1], 16),
                parseInt(body[2] + body[2], 16),
            ];
        }
        if (body.length === 6 && /^[0-9a-f]{6}$/i.test(body)) {
            return [
                parseInt(body.slice(0, 2), 16),
                parseInt(body.slice(2, 4), 16),
                parseInt(body.slice(4, 6), 16),
            ];
        }
        return null;
    }
    const match = /^rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)/i.exec(text);
    if (!match) return null;
    const channels = [Number(match[1]), Number(match[2]), Number(match[3])];
    if (channels.some(c => !isFinite(c))) return null;
    return [
        Math.max(0, Math.min(255, Math.round(channels[0]))),
        Math.max(0, Math.min(255, Math.round(channels[1]))),
        Math.max(0, Math.min(255, Math.round(channels[2]))),
    ];
}

/**
 * The colour that means "this variable did not answer".
 *
 * A value no theme would ever set deliberately, used both as the `var()`
 * fallback and as the probe's inherited colour, so an undefined variable and
 * one that is invalid at computed-value time both land on the same reading.
 */
const SENTINEL = "rgb(1, 2, 3)";

/** 0 (black) to 1 (white). Used only to decide whether a resolved theme is dark. */
function luminance(value: string): number {
    const rgb = parseColour(value);
    if (!rgb) return 0;
    return (0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]) / 255;
}

/**
 * Resolve a chain of Discord custom properties to a real colour.
 *
 * `getComputedStyle(root).getPropertyValue("--background-primary")` is not
 * enough: a custom property's value is substituted only where it is *used*, so
 * on a current client that call hands back the literal text
 * `hsl(var(--primary-630-hsl))`. Setting the chain as an element's `color` and
 * reading the computed value back makes the browser do the substitution, which
 * is why this goes through a probe node rather than reading the variable.
 *
 * This is the one place the port diverges from `palette._hex`, which declines
 * anything that is not a hex triple because Textual answers `auto 87%` for
 * several variables. A browser answers a resolved `rgb(...)`, which *is* a
 * colour, so it is accepted and used as-is.
 */
function resolveVar(probe: HTMLElement | null, names: string[], fallback: string): string {
    if (!probe) return fallback;
    for (const name of names) {
        try {
            probe.style.color = "";
            probe.style.color = `var(${name}, ${SENTINEL})`;
            if (!probe.style.color) continue;
            const computed = String(window.getComputedStyle(probe).color ?? "");
            const parsed = parseColour(computed);
            if (!parsed) continue;
            // The sentinel means the variable did not answer — either it is not
            // defined, and the fallback inside var() was used, or it is defined
            // as something that is invalid at computed-value time, in which case
            // `color` falls back to the inherited value, which the wrapper sets
            // to the same sentinel. Either way there is nothing to take.
            if (parsed[0] === 1 && parsed[1] === 2 && parsed[2] === 3) continue;
            return `rgb(${parsed[0]}, ${parsed[1]}, ${parsed[2]})`;
        } catch {
            // a hostile or missing document; the fallback is the answer
        }
    }
    return fallback;
}

/**
 * A palette built from the client's own theme, for `exportFollowTheme`.
 *
 * The port of `palette.from_theme`, and its central rule survives verbatim:
 * **verdict colours are not taken from the theme.** They are the export's
 * evidence — a THREAT row is red because it is a threat — and a client running
 * a monochrome theme would otherwise drain exactly the distinction a reader
 * scans for. The chrome follows the app; the findings keep their meaning.
 *
 * Both variable families are asked for in turn because Discord is mid-migration
 * and a given build may define either.
 */
export function paletteFromTheme(): ExportPalette {
    let holder: HTMLElement | null = null;
    let probe: HTMLElement | null = null;
    try {
        holder = document.createElement("div");
        holder.setAttribute("aria-hidden", "true");
        holder.style.position = "absolute";
        holder.style.opacity = "0";
        holder.style.pointerEvents = "none";
        // the inherited colour the probe falls back to when a variable does not
        // resolve; see `resolveVar`
        holder.style.color = SENTINEL;
        probe = document.createElement("span");
        holder.appendChild(probe);
        document.body.appendChild(holder);
    } catch {
        holder = null;
        probe = null;
    }

    try {
        // Nothing to read the theme out of. Saying so by returning the fixed
        // palette is better than returning the fixed palette with a footer
        // claiming it followed a theme it never saw.
        if (!probe) return DEFAULT_PALETTE;

        const background = resolveVar(probe, ["--background-base-lower", "--background-primary"], DEFAULT_PALETTE.background);
        const dark = luminance(background) < 0.5;
        const panel = resolveVar(probe, ["--background-base-low", "--background-secondary"], DEFAULT_PALETTE.panel);
        const text = resolveVar(probe, ["--text-default", "--text-normal"], DEFAULT_PALETTE.text);
        const accent = resolveVar(probe, ["--brand-500", "--brand-experiment"], DEFAULT_PALETTE.accent);
        return {
            background,
            panel,
            stripe: resolveVar(probe, ["--background-base-lowest", "--background-secondary-alt"], panel),
            grid: resolveVar(probe, ["--border-strong", "--background-modifier-accent"], dark ? DEFAULT_PALETTE.grid : "#c8ccd2"),
            rule: resolveVar(probe, ["--border-subtle", "--background-modifier-accent"], dark ? DEFAULT_PALETTE.rule : "#dfe3e8"),
            link: resolveVar(probe, ["--text-link", "--text-brand"], DEFAULT_PALETTE.link),
            dark,
            text,
            muted: resolveVar(probe, ["--text-muted", "--text-secondary"], DEFAULT_PALETTE.muted),
            heading: text,
            accent,
            onAccent: resolveVar(probe, ["--white-500", "--white"], DEFAULT_PALETTE.onAccent),
            // the one thing the theme may not touch
            verdicts: { ...DEFAULT_VERDICT_COLOURS },
            source: "the Discord client's theme",
        };
    } catch (err) {
        logger.error("could not read the client theme; using the default export palette", err);
        return DEFAULT_PALETTE;
    } finally {
        try {
            holder?.remove();
        } catch {
            // nothing to clean up
        }
    }
}

/** Read one plugin setting. `settings.store` throws before registration. */
function setting<T>(key: string, fallback: T): T {
    return safely(() => {
        const store = (settings as any)?.store;
        if (store == null) return fallback;
        const value = store[key];
        return value === undefined || value === null ? fallback : (value as T);
    }, fallback);
}

/**
 * The palette an export is drawn in.
 *
 * Off by default: the fixed dark skin is what the terminal app produces, so two
 * exports of the same scan from two machines are the same document. Switching
 * `exportFollowTheme` on makes the chrome follow the client, which is what
 * `[export] follow_theme` does in the Python.
 */
export function resolvePalette(): ExportPalette {
    if (!setting("exportFollowTheme", false)) return DEFAULT_PALETTE;
    return paletteFromTheme();
}

// --------------------------------------------------------------------------
// retention — what is true of *this* file
//
// An exported file outlives everything the plugin can sweep: nothing expires a
// CSV sitting in somebody's downloads folder. So the file says what its own
// retention is, and it says it from the setting that was actually in force when
// it was written rather than from the rule in the abstract. Both readings are
// overridable through ExportOptions so a caller that already knows (a stored
// scan being re-exported, a test) can state the truth about that run instead of
// about this moment.
// --------------------------------------------------------------------------

/** Whether this run was told to keep findings past the terms' 24-hour window. */
export function retainedBeyondTerms(opts?: ExportOptions | null): boolean {
    if (typeof opts?.retainBeyondTerms === "boolean") return opts.retainBeyondTerms;
    return safely(() => retainBeyondTermsFrom((settings as any)?.store), false);
}

/**
 * How many hours this file is claiming for itself.
 *
 * The terms' 24 unless the ceiling has been lifted, in which case it is the
 * configured window — the number the caches are actually holding to, so the
 * file's expiry line and the plugin's own sweep cannot disagree.
 */
export function retentionWindowHours(opts?: ExportOptions | null): number {
    if (!retainedBeyondTerms(opts)) return RETENTION_HOURS;
    const asked = Number(opts?.retentionHours);
    if (isFinite(asked) && asked >= 1) return Math.floor(asked);
    return safely(() => retentionHoursFrom((settings as any)?.store), RETENTION_HOURS);
}

/**
 * How many of these findings were already past the 24-hour window.
 *
 * Independent of any setting, exactly as rsb/export.py:229 has it: results left
 * on a screen for two days are as stale as ones served from a cache that was
 * told to keep them, and a file is entitled to say so either way.
 */
export function countStale(rows: ExportRow[]): number {
    let stale = 0;
    for (const row of rows ?? []) {
        if (safely(() => isStale(row?.report), false)) stale++;
    }
    return stale;
}

