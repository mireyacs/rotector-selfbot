/**
 * One CSV field.
 *
 * RFC 4180 quoting, plus one guard the Python does not need: a leading `=`,
 * `+`, `-`, `@`, tab or carriage return makes a spreadsheet treat the cell as a
 * formula, and every free-text column here is third-party text — Roblox
 * usernames, detector messages, evidence. A finding must not be able to run
 * anything when a moderator opens the file, so those cells are prefixed with an
 * apostrophe, which spreadsheets read as "this is text".
 */
function csvField(value: string): string {
    let text = String(value ?? "");
    if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;
    if (/[",\r\n]/.test(text)) return `"${text.replace(/"/g, '""')}"`;
    return text;
}

function csvRow(values: string[]): string {
    return values.map(csvField).join(",");
}

/**
 * CSV, split into numbered segments when the list is long.
 *
 * Each part is a complete CSV with its own comment header and its own column
 * row, so every segment opens on its own — which is the whole point of
 * segmenting rather than truncating.
 *
 * The header lines are `#`-prefixed comments rather than a sidecar README,
 * because a browser hands over one file at a time and there is no folder to put
 * a README in. A spreadsheet shows them as a few rows of text above the table;
 * that is the price of the attribution and the expiry travelling with the data,
 * and the terms do not make it optional.
 */
export function exportCsv(reports: ExportInput, opts: ExportOptions = {}): string[] {
    const rows = asRows(reports);
    const columns = validColumns(opts.columns);
    const size = Math.max(0, Math.trunc(Number(opts.segmentSize ?? DEFAULT_SEGMENT_SIZE)) || 0);

    const chunks: ExportRow[][] = [];
    if (size > 0 && rows.length > size) {
        for (let i = 0; i < rows.length; i += size) chunks.push(rows.slice(i, i + size));
    } else {
        chunks.push(rows);
    }

    const notice = [
        ...headerLines(rows, opts),
        ...verdictLegend(rows),
    ];

    return chunks.map((chunk, index) => {
        const lines: string[] = [];
        for (const line of notice) lines.push(`# ${line}`);
        if (chunks.length > 1) lines.push(`# Part:      ${index + 1} of ${chunks.length}`);
        lines.push(csvRow(columns));
        for (const row of chunk) lines.push(csvRow(columns.map(column => cellValue(row, column))));
        // a trailing newline, so a shell that concatenates parts does not join
        // the last row of one to the header comment of the next
        return `${lines.join("\r\n")}\r\n`;
    });
}

