function worst(row: ExportRow) {
    return safely(() => worstAccount(row.report), null);
}

function rowVerdict(row: ExportRow): Verdict {
    return safely(() => reportVerdict(row.report), Verdict.UNKNOWN);
}

function accountsOf(row: ExportRow) {
    return safely(() => sortedAccounts(row.report), [] as ReturnType<typeof sortedAccounts>);
}

function flat(value: unknown): string {
    return String(value ?? "").replace(/[\r\n]+/g, " / ").trim();
}

export const COLUMNS: Record<string, (row: ExportRow) => string> = {
    discord_id: r => r.discordId,
    username: r => r.username,
    display_name: r => r.displayName,
    verdict: r => verdictLabel(rowVerdict(r)),
    /**
     * The meaning, beside the word.
     *
     * Not in the Python's column set, and offered here because the plugin's own
     * rule is stricter than the file format: NO DETECTIONS may never be read as
     * "safe", and a bare column of verdict words in a spreadsheet is exactly
     * where that misreading happens. It is not in DEFAULT_COLUMNS — every file
     * already prints the legend in its header — but it is available for anyone
     * who wants the sentence on the row itself.
     */
    verdict_meaning: r => verdictMeaning(rowVerdict(r)),
    /**
     * How old this answer is, when it is older than the terms' window.
     *
     * Empty for a finding inside the window, so the column costs nothing to
     * read in the ordinary case and cannot be mistaken for a verdict of its
     * own. A value here means the row is a claim about a day or more ago —
     * flag types change and appeals succeed, so the reader is owed that before
     * they act on it. rsb/export.py:80 writes the same cell.
     */
    stale: r => (isStale(r.report) ? `${describeAge(reportAge(r.report))} old` : ""),
    flag: r => flagName(worst(r)?.flagType ?? null),
    actionable: r => String(flagIsActionable(worst(r)?.flagType ?? null)),
    category: r => categoryName(worst(r)?.category ?? null) ?? "",
    confidence: r => {
        const c = worst(r)?.confidence;
        return typeof c === "number" && isFinite(c) ? c.toFixed(2) : "";
    },
    roblox_accounts: r => accountsOf(r).map(a => `${a.username}(${a.userId})`).join(" "),
    roblox_ids: r => accountsOf(r).map(a => String(a.userId)).join(" "),
    roblox_profiles: r => accountsOf(r).map(a => safely(() => profileUrl(a), "")).join(" "),
    detection_sources: r => accountsOf(r).map(a => sourceNames(a.sources)).join(" "),
    tracked_servers: r => String(r.report?.servers?.length ?? 0),
    tracked_server_names: r => (r.report?.servers ?? []).map(s => String(s?.serverName ?? "")).join(" | "),
    reasons: r => {
        const out: string[] = [];
        for (const account of accountsOf(r)) {
            for (const [name, detail] of Object.entries(account.reasons ?? {})) {
                out.push(`${name}: ${flat((detail as any)?.message)}`);
            }
        }
        return out.join(" | ");
    },
    evidence: r => {
        const out: string[] = [];
        for (const account of accountsOf(r)) {
            for (const detail of Object.values(account.reasons ?? {})) {
                for (const item of ((detail as any)?.evidence ?? []) as unknown[]) out.push(flat(item));
            }
        }
        return out.join(" | ");
    },
    /**
     * A lookup that did not answer. Never blank-by-omission: an empty verdict
     * column with no error beside it would read as "checked, nothing found",
     * and an outage is not a clean result.
     */
    error: r => String(r.report?.error ?? ""),
};

/**
 * The sensible default set (rsb/export.py:104-116), plus `error`.
 *
 * The Python leaves the error column out of its default, which means a member
 * whose lookup failed exports as `UNKNOWN / Untracked` with nothing beside it
 * saying why — indistinguishable, in a spreadsheet, from a member Rotector
 * simply does not know. The plugin refuses that reading everywhere else (the
 * ledger prints "did not answer", the summary counts it separately), so the
 * column travels by default here too. It is empty for every row that answered.
 */
export const DEFAULT_COLUMNS: string[] = [
    "discord_id",
    "username",
    "display_name",
    "verdict",
    // On by default (rsb/export.py:127-129), because a stale finding that is
    // not labelled reads as a current one — and the cell is blank for every
    // finding inside the window, so it costs nothing in the ordinary case.
    "stale",
    "flag",
    "actionable",
    "category",
    "confidence",
    "roblox_accounts",
    "tracked_servers",
    "reasons",
    "error",
];

export const ALL_COLUMNS: string[] = Object.keys(COLUMNS);

/** Keep only columns that exist, preserving the caller's order. */
export function validColumns(names: Iterable<string> | null | undefined): string[] {
    const seen = new Set<string>();
    const out: string[] = [];
    for (const name of names ?? []) {
        const key = String(name);
        if (COLUMNS[key] && !seen.has(key)) {
            seen.add(key);
            out.push(key);
        }
    }
    return out.length ? out : [...DEFAULT_COLUMNS];
}

/** `discord_id` -> `Discord Id`, the label the TXT and HTML print. */
export function columnLabel(name: string): string {
    return String(name)
        .replace(/_/g, " ")
        .replace(/\b\w/g, c => c.toUpperCase());
}

export function cellValue(row: ExportRow, column: string): string {
    const read = COLUMNS[column];
    if (!read) return "";
    return safely(() => String(read(row) ?? ""), "");
}

