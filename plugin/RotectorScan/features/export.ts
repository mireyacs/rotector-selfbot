/**
 * The plain-text note the Python writes beside the files.
 *
 * The terminal app can enforce the retention window — `purge_expired` deletes
 * its own folders on the next export. A renderer cannot delete a file it has
 * handed to the download manager, so this note, and the header inside every
 * file, are the whole of the enforcement. That is why it is offered alongside
 * every export rather than as an option.
 */
export function exportReadme(reports: ExportInput, opts: ExportOptions & { files?: string[]; } = {}): string {
    const rows = asRows(reports);
    const legend = verdictLegend(rows);
    const lines = [...headerLines(rows, opts), ""];
    if (opts.files?.length) {
        lines.push("Files:");
        for (const file of opts.files) lines.push(`  ${file}`);
        lines.push("");
    }
    if (legend.length) {
        lines.push("What the verdicts mean:");
        for (const line of legend) lines.push(`  ${line}`);
        lines.push("");
    }
    lines.push(
        "NO DETECTIONS means nothing has been detected yet. It is not a clean bill",
        "of health and it is never a background check.",
        "",
        ...retentionNoteLines(rows, opts, [
            `Delete these files within ${RETENTION_HOURS} hours. Rotector flag statuses change,`,
            "and their Terms of Use forbid retaining responses beyond that. Anyone",
            `listed here can appeal at ${APPEAL_URL}`,
        ]),
        "",
        MARKER,
        ""
    );
    return lines.join("\n");
}

