/**
 * One member, paired with whatever the client knows about them.
 *
 * The Python builds these in the TUI, where the username is already to hand.
 * Here the report is all a caller has, so `buildRows` fills the rest from
 * UserStore — and tolerates it being empty, because a scan can list somebody
 * who has since left and whom the client no longer holds.
 */
export interface ExportRow {
    discordId: string;
    username: string;
    displayName: string;
    /** the client's own avatar URL, used by the HTML cards; never fetched here */
    avatarUrl: string | null;
    report: MemberReport;
}

/** Reports, or rows already built from them. Both are accepted everywhere. */
export type ExportInput = MemberReport[] | ExportRow[];

function safely<T>(fn: () => T, fallback: T): T {
    try {
        const value = fn();
        return value === undefined || value === null ? fallback : value;
    } catch {
        return fallback;
    }
}

function readUser(id: string): any {
    return safely(() => (UserStore as any)?.getUser?.(id) ?? null, null);
}

function avatarFor(user: any): string | null {
    if (!user) return null;
    return safely(() => {
        const url = (IconUtils as any)?.getUserAvatarURL?.(user, false, 128);
        if (url) return url;
        return (IconUtils as any)?.getDefaultAvatarURL?.(user.id, user.discriminator) ?? null;
    }, null);
}

/** One report, as a row. Unknown members keep their id, which is what identifies them. */
export function buildRow(report: MemberReport): ExportRow {
    const id = String(report?.discordId ?? "");
    const user = readUser(id);
    const username = String(user?.username ?? "");
    const displayName = String(user?.globalName || user?.username || (id ? `Unknown member ${id}` : "Unknown member"));
    return {
        discordId: id,
        username,
        displayName,
        avatarUrl: avatarFor(user),
        report: report ?? ({ discordId: id, accounts: [], servers: [], signals: [], error: null, fetchedAt: Date.now() } as any),
    };
}

export function buildRows(reports: MemberReport[]): ExportRow[] {
    if (!Array.isArray(reports)) return [];
    return reports.filter(Boolean).map(buildRow);
}

/** Whatever the caller handed us, as rows. */
export function asRows(input: ExportInput | null | undefined): ExportRow[] {
    if (!Array.isArray(input)) return [];
    const out: ExportRow[] = [];
    for (const entry of input as any[]) {
        if (!entry) continue;
        if (entry.report && typeof entry.discordId === "string") {
            out.push(entry as ExportRow);
        } else {
            out.push(buildRow(entry as MemberReport));
        }
    }
    return out;
}

