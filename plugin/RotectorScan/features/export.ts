export function formatExtension(format: string): string {
    return format === "json" ? "json" : format === "html" ? "html" : format === "png" ? "png" : format === "txt" ? "txt" : "csv";
}

export function formatMime(format: string): string {
    switch (format) {
        case "json": return "application/json;charset=utf-8";
        case "html": return "text/html;charset=utf-8";
        case "png": return "image/png";
        case "txt": return "text/plain;charset=utf-8";
        default: return "text/csv;charset=utf-8";
    }
}

/**
 * Hand one file to the user.
 *
 * A blob URL and a programmatic `<a download>`, which is the only route a
 * renderer has: the plugin has no `native.ts`, so it cannot write to disk, and
 * everything it could write would be Rotector's data sitting somewhere nothing
 * sweeps.
 *
 * The URL is revoked afterwards rather than immediately. Revoking in the same
 * tick can cancel the download before Chromium has taken its own reference to
 * the blob; the delay is long enough for the download to have started and short
 * enough that a 20 MB image is not held for the rest of the session.
 */
export function download(name: string, data: Blob | string, mime = "text/plain;charset=utf-8"): void {
    let url = "";
    try {
        const blob = typeof data === "string"
            // The BOM is for Excel, which otherwise reads a UTF-8 CSV as the
            // system codepage and mangles every non-ASCII username in it.
            ? new Blob([mime.startsWith("text/csv") ? `\uFEFF${data}` : data], { type: mime })
            : data;
        url = URL.createObjectURL(blob);

        const anchor = document.createElement("a");
        anchor.href = url;
        anchor.download = String(name || "rotector-export");
        anchor.rel = "noopener";
        anchor.style.display = "none";
        document.body.appendChild(anchor);
        anchor.click();
        anchor.remove();
    } catch (err) {
        logger.error(`could not deliver ${name}`, err);
    } finally {
        if (url) {
            setTimeout(() => {
                try {
                    URL.revokeObjectURL(url);
                } catch {
                    // already gone
                }
            }, 10_000);
        }
    }
}

export interface DownloadFile {
    name: string;
    data: Blob | string;
    mime: string;
}

/**
 * Hand over several files, spaced out.
 *
 * Chromium drops downloads that arrive in the same burst from one gesture, and
 * a segmented export is exactly that burst — so an export of eleven CSV parts
 * would silently deliver two of them. The gap is small enough not to be felt
 * and large enough that each click is its own download.
 */
export async function downloadAll(files: DownloadFile[]): Promise<number> {
    let delivered = 0;
    for (const file of files ?? []) {
        if (!file) continue;
        download(file.name, file.data, file.mime);
        delivered++;
        await new Promise(resolve => setTimeout(resolve, 220));
    }
    return delivered;
}
