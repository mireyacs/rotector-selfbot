/** A readable report — one block per member, not a table (rsb/export.py:268-309). */
export function exportTxt(reports: ExportInput, opts: ExportOptions = {}): string {
    const rows = asRows(reports);
    const columns = validColumns(opts.columns);
    const labels: Record<string, string> = {};
    let pad = 0;
    for (const column of columns) {
        labels[column] = columnLabel(column);
        pad = Math.max(pad, labels[column].length);
    }

    const header = headerLines(rows, opts);
    const legend = verdictLegend(rows);
    const rule = "=".repeat(Math.max(1, ...header.map(h => h.length)));

    const lines: string[] = [rule, ...header, rule, ""];
    if (legend.length) {
        lines.push("What the verdicts mean:");
        for (const line of legend) lines.push(`  ${line}`);
        lines.push("");
    }

    rows.forEach((row, index) => {
        let title = `${index + 1}. ${row.displayName}`;
        if (row.username && row.username !== row.displayName) title += ` (@${row.username})`;
        lines.push(title);
        lines.push("-".repeat(title.length));
        // Spelled out per member rather than left to the Stale column, which
        // the operator can deselect: whether this block is a claim about today
        // is not a formatting preference (rsb/export.py:371-374).
        const note = safely(() => staleNote(row.report), "");
        if (note) lines.push(`  ${note}`);
        for (const column of columns) {
            const value = cellValue(row, column);
            if (!value) continue;
            lines.push(`  ${labels[column].padEnd(pad)}  ${value}`);
        }
        lines.push("");
    });

    if (!rows.length) {
        lines.push("(no members matched the selected filter)");
        lines.push("");
    }

    lines.push(
        ...retentionNoteLines(rows, opts, [
            `Delete this file within ${RETENTION_HOURS} hours. Rotector flag statuses change, and`,
            "their Terms of Use forbid retaining responses beyond that.",
            `Anyone listed here can appeal at ${APPEAL_URL}`,
        ]),
        "",
        MARKER,
        ""
    );
    return lines.join("\n");
}

