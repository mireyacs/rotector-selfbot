/*
 * RotectorScan — a Discord-client port of rotector-selfbot
 * SPDX-License-Identifier: GPL-3.0-or-later
 *
 * Rendering scan results to files, and handing them to the user.
 *
 * A port of rsb/export.py, which has the shape it does because of two of
 * Rotector's Terms of Use rather than because of taste:
 *
 *  - Every file carries the attribution line, so that a finding pasted into a
 *    ticket still says where it came from and who to appeal to.
 *  - Every file states its expiry, because the terms forbid retaining their
 *    responses beyond 24 hours. The terminal app can enforce that itself
 *    (`purge_expired` deletes its own folders); a browser cannot delete a file
 *    it handed to the download manager, so the *statement* is the only
 *    enforcement left and it is therefore not optional anywhere.
 *
 * When `retainBeyondTerms` is on, that statement says how long this file is
 * actually being kept and that the terms allow 24 hours — rather than repeating
 * a rule the run did not follow. Whoever opens the file did not make that
 * choice and is entitled to know which of the two they are holding, and to see
 * any finding in it that was already past the window labelled as stale. The
 * `stale` column and `staleNote` do that per row, whichever way the setting is
 * set: results left on screen for two days go stale by themselves.
 *
 * A long list segments into numbered CSV parts for the same reason it does in
 * the Python: a scan of tens of thousands of members produces one file nothing
 * will open, and a moderator who cannot open the export has no export.
 *
 * rsb/palette.py sits under this module rather than beside it — the HTML and
 * the PNG renderers both take their colours from here, so "match the app's
 * theme" stays one decision instead of two that can disagree.
 */

