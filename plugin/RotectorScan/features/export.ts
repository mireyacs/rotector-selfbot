export function exportJson(reports: ExportInput, opts: ExportOptions = {}): string {
    const rows = asRows(reports);
    const columns = validColumns(opts.columns);
    const stamp = opts.stamp || timestamp();

    const meanings: Record<string, string> = {};
    for (const verdict of ALL_VERDICTS) meanings[verdictName(verdict)] = verdictMeaning(verdict);

    const retained = retainedBeyondTerms(opts);
    const hours = retentionWindowHours(opts);
    const stale = countStale(rows);

    const payload = {
        scan: { label: opts.label || "members", guildId: opts.guildId || "" },
        generated_at: stamp,
        scope: opts.scope || "filtered",
        // What is true of this file, not the rule in the abstract: repeating
        // the 24-hour line over data deliberately kept longer would be a claim
        // the run did not honour. The terms are named either way.
        expires_at: retained
            ? `${expiryText(stamp, hours)} (${hours} hours after generated_at - kept past the ` +
              `${RETENTION_HOURS} hours Rotector's Terms of Use #1 allow, by the operator's choice)`
            : `${expiryText(stamp)} (${RETENTION_HOURS} hours after generated_at, Rotector Terms of Use #1)`,
        retained_beyond_terms: Boolean(retained),
        stale_findings: stale,
        stale_note: stale
            ? `${stale} finding(s) here are older than ${RETENTION_HOURS} hours. Flag types change ` +
              "and appeals succeed, so those describe the day they were answered, not today - " +
              "re-check before acting. Per-member ages are in the 'stale' column."
            : "",
        attribution: ATTRIBUTION,
        appeals: APPEAL_URL,
        coverage: opts.note || "",
        verdict_meanings: meanings,
        columns: [...columns],
        members: rows.map(row => {
            const record: Record<string, string> = {};
            for (const column of columns) record[column] = cellValue(row, column);
            return record;
        }),
    };
    return `${JSON.stringify(payload, null, 2)}\n`;
}

